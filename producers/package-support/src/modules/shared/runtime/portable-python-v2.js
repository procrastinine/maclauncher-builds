const path = require("node:path");
const Base = require("./portable-python");
const Source = require("./pinned-native-build");
const Portable = require("./portable-sdl2-fonts");
const { throwIfAborted } = require('../../../../../../lib/abort.cjs');
const PROFILE = Object.freeze(require("./portable-python-v2.json"));
const PIN = Object.freeze({ ...Base.PIN, ...PROFILE });

function linkerOptions(workRoot) {
  if (!path.isAbsolute(workRoot || "") || /[\s'"$`\\\0,]/.test(workRoot)) throw new Error("Python linker paths must be absolute and contain no shell metacharacters, spaces or commas.");
  return PROFILE.linkerOptions.map(option => option.replace("${BUILD_ROOT}", workRoot.replace(/\/$/, "")));
}
function compilerEnvironment(input) {
  const base = Base.compilerEnvironment(input);
  return { ...base, LDFLAGS: [base.LDFLAGS, ...linkerOptions(input.workRoot)].join(" ") };
}

async function buildPython(input) {
  throwIfAborted(input.signal);
  // Normalize the producer path exactly as the base profile does, including
  // /var versus /private/var aliases. N_OSO paths are generated by Apple's
  // linker and are independent of C file/debug/macro prefix maps.
  const workRoot = Portable.assertFreshBuildRoot(input.workRoot, { readOnlyRoots: [input.archive] });
  const options = linkerOptions(workRoot);
  const execute = input.dependencies?.runBuildCommand || Source.runBuildCommand;
  const result = await Base.buildPython({ ...input, workRoot, dependencies: { ...input.dependencies,
    runBuildCommand(command, args, settings) {
      return execute(command, args, { ...settings, env: { ...settings.env,
        LDFLAGS: [settings.env.LDFLAGS, ...options].join(" ") } });
    } } });
  return { ...result, version: PIN.version, baseProfile: PROFILE.baseProfile,
    linkerOptions: options, objectSymbolPaths: PROFILE.objectSymbolPaths };
}

module.exports = { ...Base, PIN, PROFILE, linkerOptions, compilerEnvironment, buildPython };
