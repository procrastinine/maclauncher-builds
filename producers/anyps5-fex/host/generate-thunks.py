# Generates the per-signature thunk table for the AnyPS5 exports that the given arm64 objects define.
#
# Each export is an APS5_VABI function declared in the AnyPS5 headers that the object's source file includes; the
# generated C++ includes those headers, so each thunk is instantiated from the export's own prototype (SysVThunk.h). An export whose name ends in
# _nid_postfix is listed under the name without it, which is the name its NID is computed from.
# Variadic exports are left out (they need the va_list path); prototypes the thunks do not cover yet compile to
# nullptr through SysV::ThunkFor.
#
# Usage: generate-thunks.py <out.cpp> <include dir> <source.cpp>... -- <arm64 object>...
import re
import subprocess
import sys

out, include, rest = sys.argv[1], sys.argv[2], sys.argv[3:]
sources, objects = rest[:rest.index('--')], rest[rest.index('--') + 1:]
headers = []
for source in sources:
    for header in re.findall(r'^#include "(prx/[^"]+\.hpp)"', open(source, encoding='utf-8').read(), re.M):
        if header not in headers:
            headers.append(header)

defined = set()
for obj in objects:
    listing = subprocess.run(['nm', '-gU', obj], check=True, capture_output=True, text=True).stdout
    for line in listing.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in 'TtDdSs':
            defined.add(parts[2].removeprefix('_'))

declaration = re.compile(r'\bAPS5_VABI\s+(\w+)\s*\(([^;{]*)\)\s*(?:noexcept\s*)?;', re.S)
entries, variadic = [], []
for header in headers:
    text = open(f'{include}/{header}', encoding='utf-8').read()
    for match in declaration.finditer(text):
        name, parameters = match.group(1), match.group(2)
        if name not in defined or name.endswith('_nid_no_patch'):
            continue
        if '...' in parameters:
            variadic.append(name)
            continue
        entries.append(name)

names = sorted(set(entries))
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by producers/anyps5-fex/host/generate-thunks.py; not edited by hand.\n')
    f.write('#include "SysVThunk.h"\n')
    for header in headers:
        f.write(f'#include "{header}"\n')
    f.write('\nextern const std::pair<const char*, FexGuest::Thunk> GeneratedThunks[] = {\n')
    for name in names:
        f.write(f'  {{"{name.removesuffix("_nid_postfix")}", SysV::ThunkFor<&::{name}>()}},\n')
    f.write('  {nullptr, nullptr},\n};\n')
    f.write(f'extern const std::size_t GeneratedThunkCount = {len(names)};\n')
    if variadic:
        f.write('// Variadic exports left out: ' + ', '.join(sorted(set(variadic))) + '\n')
print(f'{len(names)} generated thunks, {len(set(variadic))} variadic exports left out')
