// AnyPS5's VideoOut and AgcDriver run SDL and the game window on the process's main thread, through
// Aps5RunOnMainThread (libkernel's MainThreadMacOs.cpp on the Rosetta route). Here the game runs on a second thread and
// the main thread serves the main dispatch queue until the game ends the process.
namespace MainThread {
std::atomic<bool> Serving {false};
struct Invocation {
  void (*Function)(void*);
  void* Context;
  std::exception_ptr Error;
};
void Invoke(void* Argument) {
  auto& Call = *static_cast<Invocation*>(Argument);
  try {
    Call.Function(Call.Context);
  } catch (...) {
    Call.Error = std::current_exception();
  }
}
void KeepAlive(CFRunLoopTimerRef, void*) {}
} // namespace MainThread

extern "C" void Aps5RunOnMainThread_nid_no_patch(void (*Function)(void*), void* Context) {
  if (!Function) {
    throw std::invalid_argument("Darwin main-thread callback is null");
  }
  if (pthread_main_np() != 0) {
    Function(Context);
    return;
  }
  if (!MainThread::Serving.load(std::memory_order_acquire)) {
    throw std::runtime_error("Darwin main-thread service is unavailable");
  }
  MainThread::Invocation Call {Function, Context, nullptr};
  dispatch_sync_f(dispatch_get_main_queue(), &Call, MainThread::Invoke);
  if (Call.Error) {
    std::rethrow_exception(Call.Error);
  }
}

namespace {
int RunGame(int argc, char** argv) {
  const std::string Mode = argc == 5 ? argv[4] : "";
  if (Mode != "modules" && Mode != "eboot-only" && Mode != "past-main" && Mode != "run") {
    std::fprintf(stderr, "usage: %s <game directory> <game data directory> <main vaddr> modules|eboot-only|past-main|run\n", argv[0]);
    return 2;
  }
  FexGuest::DescribeGuestAddress = Describe;
  FexGuest::InstallFaultReport();
  FexGuest::InstallGuestCpuHost();
  FexGuest::InitConfig();
  std::error_code Error;
  const std::string Directory = std::filesystem::absolute(argv[1], Error).string();
  // The game's own AnyPS5 folder (games/<id>/modules/anyps5 in the launcher profile) holds its writable mounts. The
  // process works in it, as libc resolves a guest path outside every mount against the working directory.
  const std::filesystem::path Data = std::filesystem::absolute(argv[2], Error);
  if (Error || !std::filesystem::is_directory(Data)) {
    std::fprintf(stderr, "game data directory %s does not exist\n", argv[2]);
    return 2;
  }
  for (const char* Mount : {"download0", "data"}) {
    std::filesystem::create_directories(Data / Mount, Error);
    if (Error) {
      std::fprintf(stderr, "cannot create %s: %s\n", (Data / Mount).c_str(), Error.message().c_str());
      return 2;
    }
  }
  std::filesystem::current_path(Data);
  // The game directory is the guest's /app0; /download0 and /data are the game data folder's subdirectories.
  AddPathAlias_nid_no_patch("/app0", Directory.c_str());
  AddPathAlias_nid_no_patch("/download0", (Data / "download0").c_str());
  AddPathAlias_nid_no_patch("/data", (Data / "data").c_str());
  const std::uint64_t MainOffset = std::strtoull(argv[3], nullptr, 0);

  // The host's thread layer first: its exports' objects are host records that AnyPS5's own thread code cannot read.
  for (std::size_t i = 0; i < GuestThreads::FunctionCount; ++i) {
    const auto& [Name, Thunk] = GuestThreads::Functions[i];
    const auto Nid = Nid::ComputeNid(Name, "");
    if (HostByNid.try_emplace(Nid, Table.size()).second) {
      NameByNid.emplace(Nid, Name);
      Source[Nid] = 1;
      Table.push_back(Thunk);
      TableNids.push_back(Nid);
    }
  }
  // Then generated thunks of AnyPS5 exports, then the stand-ins for what is not built for arm64 yet.
  std::size_t Unsupported = 0, GeneratedThunkCount = 0, ThreadExports = 0;
  for (std::size_t Part = 0; Part < GeneratedThunkPartCount; ++Part) {
    const auto [Thunks, Count] = GeneratedThunkParts[Part];
    GeneratedThunkCount += *Count;
    for (std::size_t i = 0; i < *Count; ++i) {
      const auto& [Name, Thunk] = Thunks[i];
      if (!Thunk) {
        ++Unsupported;
        continue;
      }
      if (GuestThreads::OwnsExport(Name)) {
        ++ThreadExports;
        continue;
      }
      const auto Nid = Nid::ComputeNid(Name, "");
      if (HostByNid.try_emplace(Nid, Table.size()).second) {
        NameByNid.emplace(Nid, Name);
        Source[Nid] = 0;
        Table.push_back(Thunk);
        TableNids.push_back(Nid);
      }
    }
  }
  for (const auto& [Name, Thunk] : HostFunctions) {
    const auto Nid = Nid::ComputeNid(Name, "");
    if (HostByNid.try_emplace(Nid, Table.size()).second) {
      NameByNid.emplace(Nid, Name);
      Source[Nid] = 1;
      Table.push_back(Thunk);
      TableNids.push_back(Nid);
    }
  }
  FirstStub = Table.size();
  for (std::size_t i = 0; i < GeneratedDataCount; ++i) {
    DataByNid.try_emplace(Nid::ComputeNid(GeneratedData[i].first, ""), GeneratedData[i]);
  }
  std::printf("%zu generated thunks (%zu more exports have prototypes the thunks do not cover yet, %zu thread exports left to "
              "the host's thread layer), %zu stand-in host functions, %zu thread functions\n",
              GeneratedThunkCount - Unsupported - ThreadExports, Unsupported, ThreadExports, std::size(HostFunctions), GuestThreads::FunctionCount);
  for (const char* Name : {"__stack_chk_guard", "__progname"}) {
    NameByNid.emplace(Nid::ComputeNid(Name, ""), Name);
  }
  FexGuest::MapStubs(FexGuest::MaximumThunks);

  const std::string EbootPath = std::filesystem::exists(Directory + "/eboot.elf") ? Directory + "/eboot.elf" : Directory + "/eboot.bin";
  auto Eboot = Ps5::Load(EbootPath, "eboot.elf");
  std::vector<Ps5::Module> Prx;
  if (Mode != "eboot-only") {
    for (const auto& Name : SceModules(Directory)) {
      Prx.push_back(Ps5::Load(Directory + "/sce_module/" + Name, Name));
    }
  }
  Modules.push_back(&Eboot);
  for (auto& M : Prx) {
    Modules.push_back(&M);
  }
  // AnyPS5's libraries find the guest images, and the main image's process parameters, through dl_iterate_phdr.
  for (auto* M : Modules) {
    FexGuest::RegisterGuestImage({M == &Eboot ? "" : M->Name.c_str(), M->Base, M->ProgramHeaders.data(), M->ProgramHeaderCount});
  }
  Ps5::LayOutStaticTls(Modules);
  Kernel::ProcParam = Eboot.ProcParam;
  for (auto* M : Modules) {
    Ps5::Relocate(*M, [M](const Ps5::Symbol& S) { return Resolve(*M, S); });
  }
  Kernel::ThreadPointer = Ps5::AllocateStaticTls();
  GuestThreads::AdoptInitialThread(Kernel::ThreadPointer);
  if (Table.size() > FexGuest::MaximumThunks) {
    std::printf("%zu imports exceed the stub page\nFAIL\n", Table.size());
    return 1;
  }
  std::printf("imports by NID: %zu bound to guest exports, %zu to generated thunks, %zu to stand-in host functions, %zu data, %zu stubs\n",
              Bound.Guest.size(), Bound.Generated.size(), Bound.StandIn.size(), Bound.Data.size(), Bound.Stub.size());

  const bool StopAtMain = Mode != "run";
  const std::uint64_t Main = StopAtMain ? Eboot.Base + MainOffset : 0;
  const std::uint8_t MainByte = StopAtMain ? *reinterpret_cast<std::uint8_t*>(Main) : 0;
  if (StopAtMain) {
    *reinterpret_cast<std::uint8_t*>(Main) = 0xF4;
  }
  std::uint64_t ThunkCalls = 0;
  ThunkCallCounter = &ThunkCalls;
  FexGuest::CPUState State {};
  State.fs_cached = Kernel::ThreadPointer;
  for (auto& M : Prx) {
    if (M.Init == 0) {
      continue;
    }
    State.rip = M.Init;
    State.gregs[FexGuest::X86::REG_RSP] = FexGuest::MapStack();
    FexGuest::Run(State, Table, ThunkCalls);
    std::printf("%s DT_INIT returned\n", M.Name.c_str());
  }

  // The PS5 argument block: argc, then argv.
  auto* Arguments = static_cast<std::uint64_t*>(FexGuest::MapGuest(0x4000));
  std::strcpy(reinterpret_cast<char*>(Arguments + 8), "eboot.bin");
  Arguments[0] = 1;
  Arguments[1] = reinterpret_cast<std::uint64_t>(Arguments + 8);
  Arguments[2] = 0;
  FexGuest::CPUState Start {};
  Start.fs_cached = Kernel::ThreadPointer;
  Start.rip = Eboot.Base + Eboot.Entry;
  Start.gregs[FexGuest::X86::REG_RSP] = FexGuest::MapStack();
  Start.gregs[FexGuest::X86::REG_RDI] = reinterpret_cast<std::uint64_t>(Arguments);
  // Every 5 s for 55 s: the host call and stub counts, and the guest rip a SIGUSR2 sample of this thread reads.
  const auto Watch = [&ThunkCalls] {
    struct sigaction Sample {};
    Sample.sa_sigaction = SampleGuest;
    Sample.sa_flags = SA_SIGINFO;
    sigaction(SIGUSR2, &Sample, nullptr);
    const pthread_t GuestThread = pthread_self();
    std::thread([GuestThread, &ThunkCalls] {
      for (int Second = 5; Second <= 55; Second += 5) {
        std::this_thread::sleep_for(std::chrono::seconds(5));
        std::printf("watch %ds: %llu host calls past main, %llu stub calls\n", Second,
                    static_cast<unsigned long long>(ThunkCalls - HostCallsAtMain), static_cast<unsigned long long>(StubCalls));
        pthread_kill(GuestThread, SIGUSR2);
      }
    }).detach();
  };
  if (!StopAtMain) {
    std::printf("running _start\n");
    Watch();
    FexGuest::Run(Start, Table, ThunkCalls);
    std::printf("_start returned to the host after %llu host calls, %llu of them to stubs\n", static_cast<unsigned long long>(ThunkCalls),
                static_cast<unsigned long long>(StubCalls));
    std::fflush(stdout);
    std::_Exit(0);
  }
  const auto& Final = FexGuest::Run(Start, Table, ThunkCalls, Main);
  if (Final.rip != Main) {
    std::printf("_start returned without reaching main\nFAIL\n");
    return 1;
  }
  const auto Argc = static_cast<std::uint32_t>(Final.gregs[FexGuest::X86::REG_RDI]);
  const auto* Argv = reinterpret_cast<const std::uint64_t*>(Final.gregs[FexGuest::X86::REG_RSI]);
  std::printf("reached main(argc=%u, argv[0]=\"%s\") after %llu host calls, %llu of them to stubs\n", Argc,
              Argc ? reinterpret_cast<const char*>(Argv[0]) : "", static_cast<unsigned long long>(ThunkCalls),
              static_cast<unsigned long long>(StubCalls));
  const bool Pass = StubCalls == 0 && Argc == 1 && std::strcmp(reinterpret_cast<const char*>(Argv[0]), "eboot.bin") == 0;
  if (Mode != "past-main" || !Pass) {
    std::printf("%s\n", Pass ? "PASS" : "FAIL");
    return Pass ? 0 : 1;
  }

  // Past main: the original first byte goes back, FEX drops the block it compiled with the HLT, and main runs with the
  // arguments _start passed. Each unbound import logs its NID once; the run ends at the guest's _exit, a fault or the
  // caller's time limit.
  *reinterpret_cast<std::uint8_t*>(Main) = MainByte;
  FexGuest::InvalidateGuestCode(FexGuest::Thread, Main, 1);
  HostCallsAtMain = ThunkCalls;
  FexGuest::CPUState Next {};
  Next.rip = Main;
  std::memcpy(Next.gregs, Final.gregs, sizeof(Next.gregs));
  Next.fs_cached = Final.fs_cached;
  Next.gs_cached = Final.gs_cached;
  std::printf("running main\n");
  Watch();
  FexGuest::Run(Next, Table, ThunkCalls);
  std::printf("main and _start returned to the host after %llu host calls past main, %llu of them to stubs\n",
              static_cast<unsigned long long>(ThunkCalls - HostCallsAtMain), static_cast<unsigned long long>(StubCalls));
  // The watch thread still reads ThunkCalls: end the process without unwinding main's frame.
  std::fflush(stdout);
  std::_Exit(0);
}
} // namespace

int main(int argc, char** argv) {
  // An exception no AnyPS5 caller catches ends the run; its message and the system range's mappings are reported.
  std::set_terminate([] {
    if (const auto Error = std::current_exception()) {
      try {
        std::rethrow_exception(Error);
      } catch (const std::exception& Exception) {
        std::fprintf(stderr, "uncaught exception: %s\n", Exception.what());
      } catch (...) {
        std::fprintf(stderr, "uncaught exception of an unknown type\n");
      }
    }
    std::fprintf(stderr, "mappings in the system range 0x%llx-0x%llx:\n", static_cast<unsigned long long>(SystemRange::Begin),
                 static_cast<unsigned long long>(SystemRange::End));
    SystemRange::Describe(SystemRange::Begin, SystemRange::End);
    std::abort();
  });
  struct Arguments {
    int Count;
    char** Values;
  } Game {argc, argv};
  pthread_attr_t Attributes;
  pthread_attr_init(&Attributes);
  pthread_attr_setstacksize(&Attributes, std::size_t {64} << 20);
  MainThread::Serving.store(true, std::memory_order_release);
  pthread_t Thread;
  const int Started = pthread_create(&Thread, &Attributes, [](void* Argument) -> void* {
    const auto& Game = *static_cast<const Arguments*>(Argument);
    const int Status = RunGame(Game.Count, Game.Values);
    std::fflush(stdout);
    std::exit(Status);
  }, &Game);
  pthread_attr_destroy(&Attributes);
  if (Started != 0) {
    std::fprintf(stderr, "cannot start the game thread: %s\n", std::strerror(Started));
    return 1;
  }
  CFRunLoopTimerRef Timer = CFRunLoopTimerCreate(nullptr, 1.0e10, 1.0e10, 0, 0, MainThread::KeepAlive, nullptr);
  CFRunLoopAddTimer(CFRunLoopGetMain(), Timer, kCFRunLoopCommonModes);
  for (;;) {
    CFRunLoopRun();
  }
}
