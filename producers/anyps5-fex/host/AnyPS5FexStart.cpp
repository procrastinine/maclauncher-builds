// Handles are positions in Modules from 1: the eboot is 1, its PRX modules follow, then the modules loaded later.
int HandleOf(const Ps5::Module* M) {
  return static_cast<int>(std::find(Modules.begin(), Modules.end(), M) - Modules.begin()) + 1;
}
Ps5::Module* ModuleOf(int Handle) {
  return Handle >= 1 && static_cast<std::size_t>(Handle) <= Modules.size() ? Modules[Handle - 1] : nullptr;
}
Ps5::Module* Containing(std::uint64_t Address) {
  for (auto* M : Modules) {
    if (Address >= M->Base && Address - M->Base < M->Size) {
      return M;
    }
  }
  return nullptr;
}

// A guest /app0 path's host file: the original executable first (Media/Modules/*.prx of a prepared AnyPS5 game is the
// SELF in app0 and the ELF in its source folder), then the game directory.
std::string HostPath(std::string_view Path) {
  if (!Path.starts_with("/app0/")) {
    return {};
  }
  const std::string Rest(Path.substr(5));
  for (const auto& Root : {Executables, Directory}) {
    if (std::filesystem::is_regular_file(Root + Rest)) {
      return Root + Rest;
    }
  }
  return {};
}

// Imports of the other modules that name M were bound before M was here (to logging stubs); they bind to M's exports
// now, as the PS5 runtime linker binds them when the module is loaded.
std::size_t Rebind(Ps5::Module& M) {
  constexpr std::uint32_t R_64 = 1, R_GLOB_DAT = 6, R_JUMP_SLOT = 7;
  std::size_t Count = 0;
  for (auto* Other : Modules) {
    if (Other == &M) {
      continue;
    }
    for (const auto& R : Other->Relocations) {
      if (R.Symbol == 0 || (R.Type != R_64 && R.Type != R_GLOB_DAT && R.Type != R_JUMP_SLOT)) {
        continue;
      }
      const auto& S = Other->Symbols.at(R.Symbol);
      const auto Declared = S.Section == 0 ? Ps5::DeclaredModule(*Other, S.Name) : std::string {};
      if (Declared.empty() || !Ps5::Provides(M, Declared)) {
        continue;
      }
      if (const auto Export = M.Exports.find(Ps5::NidOf(S.Name)); Export != M.Exports.end()) {
        *reinterpret_cast<std::uint64_t*>(Other->Base + R.Offset) = Export->second + R.Addend;
        ++Count;
      }
    }
  }
  return Count;
}

int LoadStartModule(const char* Path, std::uint64_t Arguments, std::uint64_t ArgumentPointer, std::uint32_t, const void*, int* Result) {
  if (Result) {
    *Result = 0;
  }
  if (!Path) {
    return ErrorFault;
  }
  std::lock_guard Guard(Lock);
  const std::string Name = std::filesystem::path(Path).filename().string();
  for (auto* M : Modules) {
    if (M->Name == Name) {
      std::printf("sceKernelLoadStartModule %s: already loaded\n", Path);
      return HandleOf(M);
    }
  }
  const auto File = HostPath(Path);
  if (File.empty()) {
    std::printf("sceKernelLoadStartModule %s: no guest module there; SCE_KERNEL_ERROR_ENOENT\n", Path);
    return ErrorNoEntry;
  }
  auto M = std::make_unique<Ps5::Module>(Ps5::Load(File, Name));
  if (!Ps5::AddRuntimeTls(*M)) {
    std::printf("sceKernelLoadStartModule %s: its %llu-byte TLS block does not fit in the static TLS surplus\n", Path,
                static_cast<unsigned long long>(M->TlsMemSize));
    return ErrorNoMemory;
  }
  Modules.push_back(M.get());
  FexGuest::RegisterGuestImage({M->Name.c_str(), M->Base, M->ProgramHeaders.data(), M->ProgramHeaderCount});
  Ps5::Relocate(*M, [&M](const Ps5::Symbol& S) { return Resolve(*M, S); });
  const auto Rebound = Rebind(*M);
  FexGuest::ActiveThunks = Table; // the slots this module's imports added
  std::printf("loaded %s for %s; %zu earlier imports bound to it\n", M->Name.c_str(), Path, Rebound);
  int Started = 0;
  if (M->Init) {
    const std::uint64_t StartArguments[] = {Arguments, ArgumentPointer, 0};
    Started = static_cast<int>(FexGuest::CallGuest(M->Init, StartArguments, {}).Rax);
    std::printf("%s module start returned %d\n", M->Name.c_str(), Started);
  }
  if (Result) {
    *Result = Started;
  }
  const int Handle = HandleOf(M.get());
  Loaded.push_back(std::move(M));
  return Handle;
}

// The module stays loaded: other modules' imports keep pointing into it.
int StopUnloadModule(int Handle, std::uint64_t, std::uint64_t, std::uint32_t, const void*, int* Result) {
  if (Result) {
    *Result = 0;
  }
  std::lock_guard Guard(Lock);
  return ModuleOf(Handle) ? 0 : ErrorNoSuch;
}

int Dlsym(int Handle, const char* Symbol, std::uint64_t* Address) {
  if (!Symbol || !Address) {
    return ErrorFault;
  }
  std::lock_guard Guard(Lock);
  auto* M = ModuleOf(Handle);
  if (!M) {
    return ErrorNoSuch;
  }
  const auto Export = M->Exports.find(Nid::ComputeNid(Symbol, ""));
  if (Export == M->Exports.end()) {
    std::printf("sceKernelDlsym(%s, %s): no such export\n", M->Name.c_str(), Symbol);
    return ErrorNoSuch;
  }
  *Address = Export->second;
  return 0;
}

// A DWARF pointer encoding's value at Cursor (the encodings eh_frame_hdr uses), advancing Cursor.
std::uint64_t ReadEncoded(std::uint64_t& Cursor, std::uint8_t Encoding, std::uint64_t Header) {
  const std::uint64_t At = Cursor;
  std::uint64_t Value = 0;
  switch (Encoding & 0x0f) {
  case 0x00: Value = Ps5::Guest<std::uint64_t>(Cursor); Cursor += 8; break;
  case 0x03: Value = Ps5::Guest<std::uint32_t>(Cursor); Cursor += 4; break;
  case 0x0b: Value = static_cast<std::uint64_t>(static_cast<std::int64_t>(Ps5::Guest<std::int32_t>(Cursor))); Cursor += 4; break;
  case 0x04:
  case 0x0c: Value = Ps5::Guest<std::uint64_t>(Cursor); Cursor += 8; break;
  default: return 0;
  }
  switch (Encoding & 0x70) {
  case 0x10: Value += At; break;
  case 0x30: Value += Header; break;
  default: break;
  }
  return Value;
}

bool Fill(Ps5::Module& M, ModuleInfoEx& Info) {
  Info = {};
  Info.Size = sizeof(Info);
  std::string Name = M.Name == "eboot.elf" ? "eboot.bin" : M.Name;
  std::snprintf(Info.Name, sizeof(Info.Name), "%s", Name.c_str());
  Info.Id = HandleOf(&M);
  Info.TlsIndex = static_cast<std::uint32_t>(M.TlsIndex);
  if (M.TlsMemSize) {
    Info.TlsInitAddress = M.Base + M.TlsImage;
    Info.TlsInitSize = static_cast<std::uint32_t>(M.TlsFileSize);
    Info.TlsSize = static_cast<std::uint32_t>(M.TlsMemSize);
    Info.TlsOffset = static_cast<std::uint32_t>(M.TlsOffset);
    Info.TlsAlign = static_cast<std::uint32_t>(M.TlsAlign);
  }
  Info.InitAddress = M.Init;
  Info.ReferenceCount = 1;
  std::uint64_t SegmentEnd = 0;
  for (std::uint16_t i = 0; i < M.ProgramHeaderCount; ++i) {
    const auto* H = M.ProgramHeaders.data() + i * 56;
    std::uint32_t Type, Flags;
    std::uint64_t VAddr, MemSize;
    std::memcpy(&Type, H, 4);
    std::memcpy(&Flags, H + 4, 4);
    std::memcpy(&VAddr, H + 16, 8);
    std::memcpy(&MemSize, H + 40, 8);
    if (Type == 1 && Info.SegmentCount < 4) {
      Info.Segments[Info.SegmentCount++] = {M.Base + VAddr, static_cast<std::uint32_t>(MemSize),
                                            static_cast<std::int32_t>(((Flags & 4) ? 1 : 0) | ((Flags & 2) ? 2 : 0) | ((Flags & 1) ? 4 : 0))};
    } else if (Type == 0x6474e550) { // PT_GNU_EH_FRAME
      const std::uint64_t Header = M.Base + VAddr;
      Info.EhFrameHeaderAddress = Header;
      Info.EhFrameHeaderSize = static_cast<std::uint32_t>(MemSize);
      std::uint64_t Cursor = Header + 4;
      Info.EhFrameAddress = ReadEncoded(Cursor, Ps5::Guest<std::uint8_t>(Header + 1), Header);
    }
  }
  // eh_frame's size: its CIE and FDE records up to the zero terminator, which the size includes, within the image.
  if (Info.EhFrameAddress >= M.Base && Info.EhFrameAddress < M.Base + M.Size) {
    SegmentEnd = M.Base + M.Size;
    std::uint64_t Cursor = Info.EhFrameAddress;
    while (Cursor + 4 <= SegmentEnd) {
      const std::uint32_t Length = Ps5::Guest<std::uint32_t>(Cursor);
      if (Length == 0) {
        Cursor += 4;
        break;
      }
      Cursor += Length == 0xffffffffu ? 12 + Ps5::Guest<std::uint64_t>(Cursor + 4) : 4ull + Length;
    }
    Info.EhFrameSize = static_cast<std::uint32_t>(std::min(Cursor, SegmentEnd) - Info.EhFrameAddress);
  }
  return Info.SegmentCount != 0;
}

int GetModuleInfoFromAddr(std::uint64_t Address, int Flags, ModuleInfoEx* Info) {
  if (Flags != 1 && Flags != 2) {
    if (Info) {
      *Info = {};
    }
    return ErrorInvalid;
  }
  if (!Info) {
    return ErrorFault;
  }
  auto* M = Containing(Address);
  if (!M || !Fill(*M, *Info)) {
    *Info = {};
    return ErrorNoSuch;
  }
  return 0;
}

int GetModuleInfoForUnwind(std::uint64_t Address, int, ModuleInfoForUnwind* Info) {
  if (!Info) {
    return ErrorFault;
  }
  auto* M = Containing(Address);
  ModuleInfoEx Image;
  if (!M || !Fill(*M, Image)) {
    return ErrorNoSuch;
  }
  Info->Size = sizeof(ModuleInfoForUnwind);
  std::memcpy(Info->Name, Image.Name, sizeof(Info->Name));
  Info->EhFrameHeaderAddress = Image.EhFrameHeaderAddress;
  Info->EhFrameAddress = Image.EhFrameAddress;
  Info->EhFrameSize = Image.EhFrameSize;
  Info->Segment0Address = Image.Segments[0].Address;
  Info->Segment0Size = Image.Segments[0].Size;
  return 0;
}

// FreeBSD libc's __elf_phdr_match_addr: whether an address is in an executable segment of the image a dl_phdr_info (or,
// as AnyPS5 accepts too, a ModuleInfoEx) describes.
int PhdrMatchAddr(const void* PhdrInfo, std::uint64_t Address) {
  if (!PhdrInfo) {
    return 0;
  }
  const auto* Module = static_cast<const ModuleInfoEx*>(PhdrInfo);
  if (Module->Size == sizeof(ModuleInfoEx)) {
    for (std::uint32_t i = 0; i < Module->SegmentCount && i < 4; ++i) {
      const auto& S = Module->Segments[i];
      if ((S.Protection & 4) != 0 && S.Size >= 8 && S.Address <= Address && Address - S.Address <= S.Size - 8) {
        return 1;
      }
    }
    return 0;
  }
  const auto Base = Ps5::Guest<std::uint64_t>(reinterpret_cast<std::uint64_t>(PhdrInfo));
  const auto Headers = Ps5::Guest<std::uint64_t>(reinterpret_cast<std::uint64_t>(PhdrInfo) + 16);
  const auto Count = Ps5::Guest<std::uint16_t>(reinterpret_cast<std::uint64_t>(PhdrInfo) + 24);
  for (std::uint16_t i = 0; i < Count; ++i) {
    const auto H = Headers + i * 56;
    if (Ps5::Guest<std::uint32_t>(H) != 1 || (Ps5::Guest<std::uint32_t>(H + 4) & 1) == 0) {
      continue;
    }
    const auto Begin = Base + Ps5::Guest<std::uint64_t>(H + 16);
    if (Begin <= Address && Address + 8 < Begin + Ps5::Guest<std::uint64_t>(H + 40)) {
      return 1;
    }
  }
  return 0;
}

