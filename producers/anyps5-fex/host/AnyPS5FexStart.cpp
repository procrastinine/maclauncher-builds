std::vector<FexGuest::Thunk> Table;
std::vector<std::string> TableNids;
std::unordered_map<std::string, std::size_t> HostByNid;
std::unordered_map<std::string, std::string> NameByNid;
std::unordered_map<std::string, std::uint64_t> Objects;
std::unordered_map<std::string, std::pair<const char*, void*>> DataByNid;
std::vector<Ps5::Module*> Modules;
std::size_t FirstStub = 0;
std::uint64_t StubCalls = 0;
std::vector<bool> StubLogged;

// Unique imported NIDs by how they were bound.
struct Counts {
  std::unordered_map<std::string, int> Guest, Generated, StandIn, Data, Stub;
} Bound;
std::unordered_map<std::string, int> Source; // NID -> 0 generated, 1 stand-in

// Past main, a watch thread samples where the guest thread is: SIGUSR2 interrupts it, and the handler maps the host pc
// in translated code back to the guest RIP of its block. A guest that loops without calling the host shows up here.
void Describe(std::uint64_t Address, char* Text, std::size_t Size);
void SampleGuest(int, siginfo_t*, void* Context) {
  const auto PC = __darwin_arm_thread_state64_get_pc(static_cast<ucontext_t*>(Context)->uc_mcontext->__ss);
  char Text[256];
  int Length;
  if (FexGuest::CTX->IsAddressInCodeBuffer(FexGuest::Thread, PC)) {
    const auto Rip = FexGuest::CTX->RestoreRIPFromHostPC(FexGuest::Thread, PC);
    char Where[96];
    Describe(Rip, Where, sizeof(Where));
    Length = std::snprintf(Text, sizeof(Text), "sample: guest code, guest rip 0x%llx (%s)\n", static_cast<unsigned long long>(Rip), Where);
  } else {
    Dl_info Info {};
    dladdr(reinterpret_cast<void*>(PC), &Info);
    Length = std::snprintf(Text, sizeof(Text), "sample: host code at pc 0x%llx (%s), last guest rip 0x%llx\n", static_cast<unsigned long long>(PC),
                           Info.dli_sname ? Info.dli_sname : "?", static_cast<unsigned long long>(FexGuest::Thread->CurrentFrame->State.rip));
  }
  write(STDOUT_FILENO, Text, Length);
}

// "module+0xoffset" for a guest address in a loaded module.
void Describe(std::uint64_t Address, char* Text, std::size_t Size) {
  for (auto* M : Modules) {
    if (Address >= M->Base && Address - M->Base < M->Size) {
      std::snprintf(Text, Size, "%s+0x%llx", M->Name.c_str(), static_cast<unsigned long long>(Address - M->Base));
      return;
    }
  }
  std::snprintf(Text, Size, "0x%llx", static_cast<unsigned long long>(Address));
}

std::uint64_t StubAddress(std::size_t Index) {
  return FexGuest::StubBase + FexGuest::ThunkStubOffset + Index * FexGuest::ThunkStubSize;
}

// An import with no host function yet: logs its NID the first time and returns SCE_KERNEL_ERROR_ENOSYS.
FexGuest::After Unimplemented(FexGuest::CPUState& State) {
  const std::size_t Index = (State.rip - FexGuest::StubBase - FexGuest::ThunkStubOffset) / FexGuest::ThunkStubSize;
  ++StubCalls;
  if (!StubLogged[Index - FirstStub]) {
    StubLogged[Index - FirstStub] = true;
    const std::uint64_t Return = Ps5::Guest<std::uint64_t>(State.gregs[FexGuest::X86::REG_RSP]);
    char Caller[96];
    Describe(Return, Caller, sizeof(Caller));
    std::printf("import %s has no host function; called from %s (guest rip 0x%llx), returning SCE_KERNEL_ERROR_ENOSYS\n", TableNids[Index].c_str(),
                Caller, static_cast<unsigned long long>(Return));
  }
  State.gregs[FexGuest::X86::REG_RAX] = 0xFFFF'FFFF'8002'004EULL;
  return FexGuest::After::Return;
}

std::uint64_t Resolve(const Ps5::Symbol& S) {
  const std::string Nid = Ps5::NidOf(S.Name);
  for (auto* M : Modules) {
    if (auto Export = M->Exports.find(Nid); Export != M->Exports.end()) {
      Bound.Guest[Nid]++;
      return Export->second;
    }
  }
  if (S.IsObject()) {
    Bound.Data[Nid]++;
    // An object the arm64 AnyPS5 libraries own, such as libc's __stdoutp: the guest reads the library's own object.
    if (auto Owned = DataByNid.find(Nid); Owned != DataByNid.end()) {
      if (Objects.try_emplace(Nid, reinterpret_cast<std::uint64_t>(Owned->second.second)).second) {
        std::printf("data import %s bound to the arm64 AnyPS5 object %s\n", Owned->second.first, Owned->second.first);
      }
      return reinterpret_cast<std::uint64_t>(Owned->second.second);
    }
    // A data import from a system library: zeroed storage, with the values a libc reads before main.
    auto [Object, Inserted] = Objects.try_emplace(Nid, 0);
    if (Inserted) {
      auto* Storage = static_cast<std::uint64_t*>(FexGuest::MapGuest(0x4000));
      const auto Name = NameByNid.contains(Nid) ? NameByNid[Nid] : Nid;
      if (Name == "__stack_chk_guard") {
        Storage[0] = 0x5c9a'31f0'7d24'e6b1ULL;
      } else if (Name == "__progname") {
        std::strcpy(reinterpret_cast<char*>(Storage + 2), "eboot.bin");
        Storage[0] = reinterpret_cast<std::uint64_t>(Storage + 2);
      }
      Object->second = reinterpret_cast<std::uint64_t>(Storage);
      std::printf("data import %s bound to host storage\n", Name.c_str());
    }
    return Object->second;
  }
  if (auto Host = HostByNid.find(Nid); Host != HostByNid.end()) {
    if (Host->second >= FirstStub) {
      Bound.Stub[Nid]++;
    } else if (Source[Nid] == 0) {
      Bound.Generated[Nid]++;
    } else {
      Bound.StandIn[Nid]++;
    }
    return StubAddress(Host->second);
  }
  Bound.Stub[Nid]++;
  HostByNid.emplace(Nid, Table.size());
  Table.push_back(Unimplemented);
  TableNids.push_back(Nid);
  StubLogged.push_back(false);
  return StubAddress(Table.size() - 1);
}

std::vector<std::string> SceModules(const std::string& Directory) {
  std::vector<std::string> Names;
  if (DIR* Listing = opendir((Directory + "/sce_module").c_str())) {
    while (auto* Entry = readdir(Listing)) {
      const std::string Name = Entry->d_name;
      if (Name.size() > 4 && Name.compare(Name.size() - 4, 4, ".prx") == 0) {
        Names.push_back(Name);
      }
    }
    closedir(Listing);
  }
  std::sort(Names.begin(), Names.end());
  return Names;
}
